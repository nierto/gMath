#!/usr/bin/env python3
"""
mpmath references for `DecimalFixed<D>` transcendentals at several D in one
build: the compute word follows D (`Dp<D>: DecimalTier`), so every D must
give the correctly rounded value (half to even at D) on every build.

Output: tests/data/decimal_tier_refs.rs, one tuple per case
    (D, function, input raw at 10^D, expected raw at 10^D)
and atan2 cases (D, y raw, x raw, expected raw). Cases whose input or result
does not fit i128 at D are left out.

Usage: python3 scripts/generate_decimal_tier_refs.py
"""
import os
from mpmath import mp, mpf, exp, log, sqrt, sin, cos, tan, atan, atan2, asin, acos, sinh, cosh, tanh, asinh, acosh, atanh

mp.dps = 200
DS = [2, 4, 6, 9, 12, 19, 28, 38]
I128_MAX = 10**38  # a margin below i128::MAX (1.7e38), so every literal parses
ARGS = ["0.5", "1.5", "-0.75", "2", "0.1", "3.75", "0.01", "10", "-2.5", "0.99"]
FUNCS = {
    "exp": (exp, lambda x: True), "ln": (log, lambda x: x > 0), "sqrt": (sqrt, lambda x: x >= 0),
    "sin": (sin, lambda x: True), "cos": (cos, lambda x: True), "tan": (tan, lambda x: True),
    "atan": (atan, lambda x: True), "asin": (asin, lambda x: abs(x) <= 1), "acos": (acos, lambda x: abs(x) <= 1),
    "sinh": (sinh, lambda x: True), "cosh": (cosh, lambda x: True), "tanh": (tanh, lambda x: True),
    "asinh": (asinh, lambda x: True), "acosh": (acosh, lambda x: x >= 1), "atanh": (atanh, lambda x: abs(x) < 1),
}

def half_even(v):
    """Round an mpf to the nearest integer, ties to even."""
    f = mp.floor(v)
    r = v - f
    if r < mpf("0.5"):
        return int(f)
    if r > mpf("0.5"):
        return int(f) + 1
    return int(f) if int(f) % 2 == 0 else int(f) + 1

def raw(x, d):
    v = mpf(x) * mpf(10) ** d
    assert v == mp.floor(v), (x, d)
    return int(v)

out = ["// AUTO-GENERATED by scripts/generate_decimal_tier_refs.py (mpmath, 200 digits).",
       "// (D, function, input raw at 10^D, expected raw at 10^D, half to even)",
       "#[allow(dead_code)]",
       "pub const DECIMAL_TIER_REFS: &[(u8, &str, i128, i128)] = &["]
n = 0
for d in DS:
    for name, (f, dom) in FUNCS.items():
        for a in ARGS:
            x = mpf(a)
            if not dom(x):
                continue
            xr = raw(a, d)
            if abs(xr) > I128_MAX:
                continue
            er = half_even(f(x) * mpf(10) ** d)
            if abs(er) > I128_MAX:
                continue
            out.append(f'    ({d}, "{name}", {xr}, {er}),')
            n += 1
out.append("];")
# the hard corpus: arguments next to the singularities and range limits of
# each function at D, where a compute word with few guard digits misrounds
from mpmath import pi as mp_pi, log as mp_log
out.append("#[allow(dead_code)]")
out.append("pub const DECIMAL_TIER_HARD_REFS: &[(u8, &str, i128, i128)] = &[")
h = 0
for d in DS:
    one = 10 ** d
    def near_pi_half(k):
        v = mp_pi / 2 * k * one
        return [int(mp.floor(v)), int(mp.floor(v)) + 1]
    cases = {
        "tan": near_pi_half(1) + near_pi_half(3) + [15 * one // 10, 157 * one // 100],
        "asin": [one - 1, -(one - 1), one - 2, one // 2],
        "acos": [one - 1, -(one - 1), one - 2, 1, -1],
        "atanh": [one - 1, -(one - 1), one - 5, -(one - 5), 1],
        "acosh": [one + 1, one + 2, one + 10 ** (d // 2), one],
        "ln": [one - 1, one + 1, 1, one + 10 ** (d // 2), 2, 10 * one],
        "sqrt": [one - 1, one + 1, 1, 2, 2 * one, 10 ** 30],
        "exp": [int((85 - d) * one), -int(mp.floor(d * mp_log(10) * one)), -int(mp.floor(d * mp_log(10) * one)) - 1, -int(mp.floor((d + mpf("0.5") * mp_log(2) / mp_log(10)) * mp_log(10) * one))],
        "sin": [int(mp.floor(mp_pi * one)), int(mp.floor(mp_pi * one)) + 1, 10 ** 6 * one, 1, -1],
        "cos": near_pi_half(1) + [10 ** 6 * one, 1],
        "sinh": [1, -1, int((85 - d) * one)],
        "cosh": [1, int((85 - d) * one), 10],
        "tanh": [1, -1, 20 * one, int((85 - d) * one) if (85 - d) * one < 10 ** 38 else 20 * one],
        "asinh": [1, -1, 10 ** 30, -(10 ** 30)],
        "atan": [1, -1, 10 ** 30, one],
    }
    for name, xs in cases.items():
        f, dom = FUNCS[name]
        for xr in sorted(set(xs)):
            if abs(xr) > I128_MAX:
                continue
            x = mpf(xr) / one
            if not dom(x):
                continue
            try:
                v = f(x)
            except Exception:
                continue
            if not mp.isfinite(v):
                continue
            er = half_even(v * one)
            if abs(er) > I128_MAX:
                continue
            out.append(f'    ({d}, "{name}", {xr}, {er}),')
            h += 1
out.append("];")
print(f"{h} hard cases")
out.append("#[allow(dead_code)]")
out.append("pub const DECIMAL_TIER_ATAN2_REFS: &[(u8, i128, i128, i128)] = &[")
m = 0
for d in DS:
    for ya in ["1", "-1", "0.5", "2", "-0.25"]:
        for xa in ["1", "-1", "0.5", "-3", "0.01"]:
            yr, xr = raw(ya, d), raw(xa, d)
            if max(abs(yr), abs(xr)) > I128_MAX:
                continue
            er = half_even(atan2(mpf(ya), mpf(xa)) * mpf(10) ** d)
            if abs(er) > I128_MAX:
                continue
            out.append(f"    ({d}, {yr}, {xr}, {er}),")
            m += 1
out.append("];")
path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tests", "data", "decimal_tier_refs.rs")
open(path, "w").write("\n".join(out) + "\n")
print(f"{n} unary + {m} atan2 cases -> {path}")
