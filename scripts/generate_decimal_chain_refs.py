#!/usr/bin/env python3
"""mpmath references for canonical chains with decimal results: random trees
of depth 2 to 4 with decimal literal leaves (two or three places), a
transcendental at the root so the result stays in the decimal domain. The
expected value is the exact value rounded once, half to even, at the most
decimal places the format's storage word holds (its DECIMAL_STORAGE_MAX_DP,
fewer when the value does not fit), as a reduced fraction "num/den".

Tree text (prefix): "(op a b)", "d<literal>". Writes
tests/data/decimal_chain_refs.rs, one table per format.
"""
import os, random
from fractions import Fraction
from mpmath import mp, mpf, exp, log, sqrt, sin, cos, tan, atan, asin, acos, sinh, cosh, tanh, asinh, acosh, atanh, floor

mp.dps = 600
SEED = int(os.environ.get("SEED", "20261017"))
PER_FORMAT = int(os.environ.get("PER_FORMAT", "200"))
# (word bits, frac bits, storage max decimal places)
FORMATS = [(32, 10, 4), (32, 16, 4), (32, 24, 4), (64, 32, 9), (128, 64, 19), (256, 128, 38), (512, 256, 77)]
EDGE = mpf(10) ** -500
UN = {"exp": exp, "ln": log, "sqrt": sqrt, "sin": sin, "cos": cos, "tan": tan, "atan": atan, "asin": asin,
      "acos": acos, "sinh": sinh, "cosh": cosh, "tanh": tanh, "asinh": asinh, "acosh": acosh, "atanh": atanh}
BIN = {"add": lambda a, b: a + b, "sub": lambda a, b: a - b, "mul": lambda a, b: a * b, "div": lambda a, b: a / b}


def domain_ok(name, x):
    if name in ("asin", "acos", "atanh"):
        return abs(x) < 1 - EDGE
    if name == "acosh":
        return x > 1 + EDGE
    if name in ("ln", "sqrt"):
        return x > EDGE
    if name in ("exp", "sinh", "cosh"):
        return abs(x) < 20
    if name == "tan":
        return abs(cos(x)) > mpf("0.01")
    return True


class Gen:
    def __init__(self, rng, vmax):
        self.rng, self.vmax = rng, vmax

    def leaf(self):
        places = self.rng.choice([1, 2, 3])
        k = self.rng.randint(-3 * 10 ** places, 3 * 10 ** places)
        s = f"{abs(k) // 10 ** places}.{abs(k) % 10 ** places:0{places}d}"
        if k < 0:
            s = "-" + s
        return "d" + s, mpf(k) / 10 ** places

    def tree(self, depth, root=False):
        if depth == 0:
            return self.leaf()
        for _ in range(40):
            if root or self.rng.random() < 0.6:
                name = self.rng.choice(list(UN))
                a = self.tree(depth - 1)
                if a is None or not domain_ok(name, a[1]):
                    continue
                v = UN[name](a[1])
                if abs(v) < self.vmax and (v == 0 or abs(v) > mpf(10) ** -6):
                    return f"({name} {a[0]})", v
            else:
                name = self.rng.choice(list(BIN))
                a, b = self.tree(depth - 1), self.tree(self.rng.randint(0, depth - 1))
                if a is None or b is None or (name == "div" and abs(b[1]) < mpf("0.01")):
                    continue
                v = BIN[name](a[1], b[1])
                if abs(v) < self.vmax:
                    return f"({name} {a[0]} {b[0]})", v
        return None


def half_even(v):
    fl = floor(v)
    r = v - fl
    n = int(fl)
    if r > mpf("0.5") + EDGE or (abs(r - mpf("0.5")) <= EDGE and n % 2 == 1):
        n += 1
    return n


def corpus(w, f, dp, rng):
    g = Gen(rng, mpf(2) ** (w - f - 2))
    rows, seen = [], set()
    smax = 2 ** (w - 1) - 1
    while len(rows) < PER_FORMAT:
        t = g.tree(rng.randint(1, 3), root=True)
        if t is None or t[0] in seen:
            continue
        seen.add(t[0])
        d = dp
        while abs(half_even(t[1] * mpf(10) ** d)) > smax:
            d -= 1
        q = Fraction(half_even(t[1] * mpf(10) ** d), 10 ** d)
        rows.append((t[0], f"{q.numerator}/{q.denominator}"))
    return rows


def main():
    rng = random.Random(SEED)
    out = ["// GENERATED by scripts/generate_decimal_chain_refs.py (mpmath, 600 digits). Do not edit.",
           "// (tree, \"num/den\"): the exact value rounded once, half to even, at the format's",
           "// storage decimal places (fewer where it does not fit), as a reduced fraction.", ""]
    names = []
    for w, f, dp in FORMATS:
        rows = corpus(w, f, dp, rng)
        name = f"REFS_Q{w - f}_{f}"
        names.append((w, f, name))
        out.append(f"pub const {name}: &[(&str, &str)] = &[")
        out += [f'    ("{a}", "{b}"),' for a, b in rows]
        out += ["];", ""]
    arms = " ".join(f"({w}, {f}) => {n}," for w, f, n in names)
    out.append(f"pub const REFS: &[(&str, &str)] = match (BITS, FRAC_BITS) {{ {arms} _ => &[] }};")
    path = os.path.join(os.path.dirname(__file__), "..", "tests", "data", "decimal_chain_refs.rs")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
