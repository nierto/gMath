#!/usr/bin/env python3
"""References for tests/api_gaps_validation.rs (tests/data/api_gaps_refs.rs).

The public functions the 2026-10-16 coverage audit found never executed by
the suite: least_squares, projective_transform_homogeneous, raise_index /
lower_index, truncated_svd_auto, the Lie groups' act and inner_product,
DecimalFixed's batch multiply and float conversion, and the compression
ratios of the tensor decompositions.

Inputs are dyadic with at most 8 fraction bits and magnitude <= 8, stored
exactly at every gated format (8 to 256 fraction bits). References are exact
(Fraction) where the operation is a sum of products, otherwise mpmath at 140
digits printed with 120; the test parses each with the exact literal parser,
which rounds to nearest at the build's split, so one table serves every build.
Float references are the correctly rounded binary64 of the exact value
(Python's float(Fraction) rounds once, to nearest even).

Usage: python3 scripts/generate_api_gap_refs.py
"""
import random
from fractions import Fraction

from mpmath import mp, mpf, matrix, lu_solve, svd_r

mp.dps = 140
SEED = 20261016
DIGITS = 120
OUT = "tests/data/api_gaps_refs.rs"


def dy(rng, lo=-8, hi=8, bits=8):
    return Fraction(rng.randrange(lo << bits, hi << bits), 1 << bits)


def lit(v):
    if isinstance(v, Fraction):
        sign = "-" if v < 0 else ""
        v = abs(v)
        d = 0
        while (v * 10 ** d).denominator != 1:
            d += 1
            assert d <= 60, "non-dyadic exact value"
        n = int(v * 10 ** d)
        if d == 0:
            return f"{sign}{n}"
        s = str(n).rjust(d + 1, "0")
        return f"{sign}{s[:-d]}.{s[-d:]}"
    return mp.nstr(v, DIGITS, strip_zeros=False, min_fixed=-10**9, max_fixed=10**9)


def m_of(fr):
    return mpf(fr.numerator) / fr.denominator


def vl(v):
    return "&[" + ", ".join(f'"{lit(x)}"' for x in v) + "]"


def dot(a, b):
    return sum((x * y for x, y in zip(a, b)), Fraction(0))


def matvec(m, rows, cols, v):
    return [dot(m[r * cols:(r + 1) * cols], v) for r in range(rows)]


def main():
    rng = random.Random(SEED)
    out = ["// GENERATED by scripts/generate_api_gap_refs.py - do not edit.",
           "// Dyadic inputs (<= 8 fraction bits, |x| <= 8); references exact or mpmath",
           "// at 120 digits, parsed at the build's split (nearest, ties toward +inf).", ""]

    # least squares: overdetermined, full column rank, small entries so the
    # solution stays within the narrowest range
    out.append("/// (rows, cols, A row-major, b, x minimising |Ax - b|)")
    out.append("pub const LEAST_SQUARES: &[(usize, usize, &[&str], &[&str], &[&str])] = &[")
    for (m, n) in [(4, 2), (5, 3), (6, 3), (5, 2), (7, 4), (6, 4)]:
        while True:
            a = [dy(rng, -2, 2, 4) for _ in range(m * n)]
            b = [dy(rng, -2, 2, 4) for _ in range(m)]
            am = matrix(m, n)
            for i in range(m):
                for j in range(n):
                    am[i, j] = m_of(a[i * n + j])
            bm = matrix([m_of(x) for x in b])
            ata = am.T * am
            if abs(mp.det(ata)) < mpf("0.5"):
                continue
            x = lu_solve(ata, am.T * bm)
            if max(abs(x[i]) for i in range(n)) < 8:
                break
        out.append(f"    ({m}, {n}, {vl(a)}, {vl(b)}, &[" + ", ".join(f'"{lit(x[i])}"' for i in range(n)) + "]),")
    out.append("];\n")

    # projective transform: H p, a sum of products rounded once
    out.append("/// (H 3x3 row-major, p, H p)")
    out.append("pub const PROJECTIVE: &[(&[&str], &[&str], &[&str])] = &[")
    for _ in range(6):
        h = [dy(rng, -4, 4) for _ in range(9)]
        p = [dy(rng, -4, 4) for _ in range(3)]
        out.append(f"    ({vl(h)}, {vl(p)}, {vl(matvec(h, 3, 3, p))}),")
    out.append("];\n")

    # index raising / lowering keeps the index in its position:
    # R[.., a (at idx), ..] = sum_j G[a, j] T[.., j (at idx), ..]
    def lower(t, shape, idx, g):
        d = shape[idx]
        strides = [1] * len(shape)
        for k in range(len(shape) - 2, -1, -1):
            strides[k] = strides[k + 1] * shape[k + 1]
        total = len(t)
        r = [Fraction(0)] * total
        for flat in range(total):
            ix = [(flat // strides[k]) % shape[k] for k in range(len(shape))]
            a = ix[idx]
            s = Fraction(0)
            for j in range(d):
                jx = list(ix)
                jx[idx] = j
                s += g[a * d + j] * t[sum(jx[k] * strides[k] for k in range(len(shape)))]
            r[flat] = s
        return r

    out.append("/// (shape, T row-major, idx, G d x d row-major, result in T's index order)")
    out.append("pub const INDEX_MAP: &[(&[usize], &[&str], usize, &[&str], &[&str])] = &[")
    for shape, idx in [((3, 3), 0), ((3, 3), 1), ((2, 3), 1), ((3, 2), 0), ((2, 2, 2), 1), ((2, 2, 2), 2), ((2, 3, 2), 1)]:
        n = 1
        for s in shape:
            n *= s
        t = [dy(rng, -4, 4) for _ in range(n)]
        d = shape[idx]
        g = [dy(rng, -2, 2) for _ in range(d * d)]
        shp = "&[" + ", ".join(str(s) for s in shape) + "]"
        out.append(f"    ({shp}, {vl(t)}, {idx}, {vl(g)}, {vl(lower(t, list(shape), idx, g))}),")
    out.append("];\n")

    # truncated SVD with automatic rank: A = sum of two dyadic rank-one terms
    out.append("/// (rows, cols, A row-major, numerical rank, leading singular values)")
    out.append("pub const TSVD_AUTO: &[(usize, usize, &[&str], usize, &[&str])] = &[")
    for (m, n) in [(4, 3), (5, 3), (4, 4)]:
        u1 = [dy(rng, -2, 2, 3) for _ in range(m)]
        v1 = [dy(rng, -2, 2, 3) for _ in range(n)]
        u2 = [dy(rng, -2, 2, 3) for _ in range(m)]
        v2 = [dy(rng, -2, 2, 3) for _ in range(n)]
        a = [u1[i] * v1[j] + u2[i] * v2[j] for i in range(m) for j in range(n)]
        am = matrix(m, n)
        for i in range(m):
            for j in range(n):
                am[i, j] = m_of(a[i * n + j])
        s = sorted([svd_r(am, compute_uv=False)[i] for i in range(min(m, n))], reverse=True)
        assert s[2] < mpf(10) ** -100 and s[1] > mpf("0.25"), "rank-2 construction"
        out.append(f"    ({m}, {n}, {vl(a)}, 2, &[\"{lit(s[0])}\", \"{lit(s[1])}\"]),")
    out.append("];\n")

    # group actions g p (3x3) and inner products, sums of products rounded once
    out.append("/// (g 3x3 row-major, p, g p)")
    out.append("pub const ACT3: &[(&[&str], &[&str], &[&str])] = &[")
    for _ in range(4):
        g = [dy(rng, -2, 2) for _ in range(9)]
        p = [dy(rng, -4, 4) for _ in range(3)]
        out.append(f"    ({vl(g)}, {vl(p)}, {vl(matvec(g, 3, 3, p))}),")
    out.append("];\n")
    out.append("/// (SE(3) element 4x4 row-major [[R, t], [0, 1]], p, R p + t)")
    out.append("pub const ACT_SE3: &[(&[&str], &[&str], &[&str])] = &[")
    for _ in range(4):
        r = [dy(rng, -2, 2) for _ in range(9)]
        t = [dy(rng, -4, 4) for _ in range(3)]
        g = r[0:3] + [t[0]] + r[3:6] + [t[1]] + r[6:9] + [t[2]] + [Fraction(0)] * 3 + [Fraction(1)]
        p = [dy(rng, -4, 4) for _ in range(3)]
        rp = matvec(r, 3, 3, p)
        out.append(f"    ({vl(g)}, {vl(p)}, {vl([rp[i] + t[i] for i in range(3)])}),")
    out.append("];\n")
    out.append("/// (u, v, u . v) of lengths 3, 6, 4, 9")
    out.append("pub const INNER: &[(&[&str], &[&str], &str)] = &[")
    for n in [3, 6, 4, 9, 3, 6]:
        u = [dy(rng, -4, 4) for _ in range(n)]
        v = [dy(rng, -4, 4) for _ in range(n)]
        out.append(f"    ({vl(u)}, {vl(v)}, \"{lit(dot(u, v))}\"),")
    out.append("];\n")

    # DecimalFixed<D>: batch multiply (half to even at D places), to_f64_lossy
    def half_even(q):
        f = q.numerator // q.denominator
        rem = q - f
        if rem > Fraction(1, 2) or (rem == Fraction(1, 2) and f % 2 == 1):
            f += 1
        return f

    for d in (2, 4, 9, 18):
        scale = 10 ** d
        out.append(f"/// DecimalFixed<{d}>: (a raw, b raw, a * b raw, half to even)")
        out.append(f"pub const DEC_MUL_{d}: &[(i128, i128, i128)] = &[")
        for _ in range(12):
            a = rng.randrange(-10 ** (d + 3), 10 ** (d + 3))
            b = rng.randrange(-10 ** (d + 3), 10 ** (d + 3))
            out.append(f"    ({a}, {b}, {half_even(Fraction(a * b, scale))}),")
        out.append("];\n")
        out.append(f"/// DecimalFixed<{d}>: (raw, bits of the correctly rounded binary64 of raw / 10^{d})")
        out.append(f"pub const DEC_F64_{d}: &[(i128, u64)] = &[")
        raws = [rng.randrange(-10 ** (d + 6), 10 ** (d + 6)) for _ in range(40)]
        raws += [rng.randrange(-(1 << 120), 1 << 120) for _ in range(10)] + [1, -1, 3, 10 ** d + 1]
        import struct
        for r in raws:
            bits = struct.unpack("<Q", struct.pack("<d", float(Fraction(r, scale))))[0]
            out.append(f"    ({r}, 0x{bits:016x}),")
        out.append("];\n")

    with open(OUT, "w") as fh:
        fh.write("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
